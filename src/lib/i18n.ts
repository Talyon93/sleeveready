export type Language = typeof languages[number]['code'];
export function initialLanguage(): Language
{
  const pathLanguage = location.pathname.split('/').filter(Boolean)[0]?.slice(0, 2).toLowerCase();
  const requested = new URLSearchParams(location.search).get('lang')?.slice(0, 2).toLowerCase();
  const saved = localStorage.getItem('sleeveready.language');
  const candidate = (languages.some(language => language.code === pathLanguage) ? pathLanguage : undefined) ?? requested
    ?? saved ?? navigator.languages?.[0]?.slice(0, 2).toLowerCase() ?? navigator.language.slice(0, 2).toLowerCase();
  return languages.some(language => language.code === candidate) ? candidate as Language : 'en';
}
