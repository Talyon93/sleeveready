// Yes/no values ("inkable") in the page language.
export const yesNo: Record<SeoLanguage, [string, string]> = {
  en: ['Yes', 'No'],
  it: ['Sì', 'No'],
  de: ['Ja', 'Nein'],
  fr: ['Oui', 'Non'],
  es: ['Sí', 'No'],
};
export const factRows = (language: SeoLanguage, facts: CardFact[] | undefined): [string, string][] =>
  (facts ?? []).map(
    fact => [
      cardFactLabels[language][fact.key],
      fact.key === 'inkable' ? yesNo[language][fact.value === 'yes' ? 0 : 1] : fact.value,
    ],
  );
